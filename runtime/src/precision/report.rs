//! JSON and Markdown for the R4 experiment (results/r4-precision.*). Every
//! number and every generated sentence comes from the [`PrecisionResult`].

use super::experiment::{Kind, PolicyRun, PrecisionResult};
use super::policy::{Level, Site};
use crate::json::Json;

fn num(x: f64) -> Json {
    Json::Num(x)
}

fn kind_name(k: Kind) -> String {
    match k {
        Kind::Uniform(_) => "uniform".into(),
        Kind::OneSite(..) => "one site".into(),
        Kind::Mixed => "mixed".into(),
    }
}

fn run_json(r: &PolicyRun) -> Json {
    let d = &r.drift;
    Json::obj(vec![
        ("policy", Json::str(&r.policy.name)),
        ("kind", Json::str(kind_name(r.kind))),
        (
            "levels",
            Json::Arr(
                r.policy
                    .sites
                    .iter()
                    .map(|(s, l)| Json::obj(vec![("site", Json::str(s.name())), ("level", Json::str(l.name()))]))
                    .collect(),
            ),
        ),
        ("tokens", Json::uint(d.tokens)),
        ("scored_tokens", Json::uint(d.scored)),
        ("nonfinite_logits", Json::uint(d.nonfinite)),
        ("max_abs_logit_difference", num(d.max_abs)),
        ("mean_rms_logit_difference", num(d.mean_rms)),
        ("mean_kl", num(d.mean_kl)),
        ("top1_agreement", Json::uint(d.top1_agree)),
        ("perplexity", num(d.perplexity())),
        ("greedy_diverged", Json::uint(r.diverged())),
        (
            "greedy_first_divergence",
            Json::Arr(
                r.first_divergence
                    .iter()
                    .map(|x| x.map_or(Json::Null, Json::uint))
                    .collect(),
            ),
        ),
    ])
}

pub fn to_json(r: &PrecisionResult, command: &str) -> Json {
    let c = &r.config;
    Json::obj(vec![
        ("command", Json::str(command)),
        (
            "model",
            Json::obj(vec![
                ("hidden", Json::uint(c.model.hidden)),
                ("layers", Json::uint(c.model.layers)),
                ("vocab", Json::uint(c.model.vocab)),
                ("parameters", Json::uint(c.model.parameters())),
                ("seed", Json::Int(c.model.seed as i64)),
            ]),
        ),
        (
            "workload",
            Json::obj(vec![
                ("prompts", Json::uint(c.prompts)),
                ("prompt_tokens", Json::uint(c.prompt_len)),
                ("continuation_tokens", Json::uint(c.continuation)),
                ("seed", Json::Int(c.prompt_seed as i64)),
            ]),
        ),
        ("reference_perplexity", num(r.reference_perplexity)),
        ("runs", Json::Arr(r.runs.iter().map(run_json).collect())),
    ])
}

fn row(r: &PolicyRun) -> String {
    let d = &r.drift;
    let first: Vec<usize> = {
        let mut v: Vec<usize> = r.first_divergence.iter().flatten().copied().collect();
        v.sort_unstable();
        v
    };
    format!(
        "| {} | {:.4} | {:.5} | {:.2e} | {} / {} | {:.4} | {} / {} | {} | {} |\n",
        r.policy.name,
        d.max_abs,
        d.mean_rms,
        d.mean_kl,
        d.top1_agree,
        d.scored,
        d.perplexity(),
        r.diverged(),
        r.first_divergence.len(),
        first.first().map_or("–".into(), |f| f.to_string()),
        d.nonfinite
    )
}

const HEADER: &str = "| Policy | Max \\|Δz\\| | Mean RMS Δz | Mean KL | Top-1 agreement | Perplexity | Greedy diverged | Earliest divergence | Non-finite logits |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|\n";

pub fn to_markdown(r: &PrecisionResult, command: &str) -> String {
    let c = &r.config;
    let m = &c.model;
    let mut md = String::new();
    md.push_str("# R4: per-layer precision policies\n\n");
    md.push_str(&format!(
        "Generated by `{command}`. Every number below comes from that run.\n\n"
    ));
    md.push_str("## Setup\n\n");
    md.push_str(&format!(
        "- Model: the R3 decoder dimensions (hidden {}, {} layers, {} query and {} KV heads, FFN {}, vocabulary {}, {} parameters) with FP32 master weights: R3's random draws rounded once to binary32.\n",
        m.hidden, m.layers, m.q_heads, m.kv_heads, m.ffn, m.vocab, m.parameters()
    ));
    md.push_str("- Arithmetic: every matrix product is a fused chain in its site's accumulator format (exact product, one rounding per term, from +0, input index in order) on weights and input activations rounded to the site's storage format. The attention core (scores and the weighted sum of V) is a fused FP32 chain over the KV cache's stored values. RMSNorm, RoPE, softmax, SiLU and residual adds are binary32; the residual stream is binary32.\n");
    md.push_str("- Levels: `fp32` (FP32 storage and accumulation), `bf16` (BF16 storage, FP32 accumulation), `bf16-acc` (BF16 storage and accumulation), `fp16`, `fp16-acc`. Sites: each layer's attention projections (Q, K, V, O), each layer's MLP (gate, up, down), the KV cache (storage only), and the tied embedding and head.\n");
    md.push_str(&format!(
        "- Workload: {} prompts of {} tokens. The reference (all `fp32`) decodes {} tokens greedily; every policy is then run teacher-forced on those tokens, so all see the same contexts, and compared at every continuation token ({} in all). Separately each policy decodes greedily on its own.\n",
        c.prompts, c.prompt_len, c.continuation, c.prompts * c.continuation
    ));
    md.push_str(&format!(
        "- Metrics, in binary64 from the binary32 logits: max and mean RMS logit difference from the reference; mean KL(p_ref ‖ p_policy); top-1 agreement; the perplexity of the reference's continuation (the reference's own is {:.4}). With random weights the perplexity is a self-consistency measure, not a language-modeling result.\n\n",
        r.reference_perplexity
    ));

    md.push_str("## 1. Uniform policies\n\n");
    md.push_str(HEADER);
    for x in r.runs.iter().filter(|x| matches!(x.kind, Kind::Uniform(_))) {
        md.push_str(&row(x));
    }

    md.push_str("\n## 2. One site at a time\n\n");
    md.push_str("Every other site stays at `fp32`. The KV cache only stores values, so it appears at its two storage levels only. Greedy divergence: prompts (of the total) whose own greedy continuation differs from the reference's, and the earliest differing token.\n\n");
    md.push_str(HEADER);
    for x in r.runs.iter().filter(|x| matches!(x.kind, Kind::OneSite(..))) {
        md.push_str(&row(x));
    }
    md.push_str("\n### Which sites are sensitive\n\n");
    md.push_str("Sites ranked by mean KL when lowered alone, most sensitive first (the `-acc` levels have no KV-cache entry):\n\n");
    for level in Level::LOW {
        let mut v: Vec<(Site, f64, usize)> = r
            .runs
            .iter()
            .filter_map(|x| match x.kind {
                Kind::OneSite(s, l) if l == level => Some((s, x.drift.mean_kl, x.drift.top1_agree)),
                _ => None,
            })
            .collect();
        v.sort_by(|a, b| b.1.partial_cmp(&a.1).expect("finite KL"));
        md.push_str(&format!(
            "- **{}**: {}.\n",
            level.name(),
            v.iter()
                .map(|(s, kl, _)| format!("{} ({kl:.2e})", s.name()))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    md.push_str(&sensitivity_sentence(r));

    md.push_str("\n## 3. Mixed policies\n\n");
    md.push_str(HEADER);
    for x in r.runs.iter().filter(|x| x.kind == Kind::Mixed) {
        md.push_str(&row(x));
    }

    md.push_str("\n## What this does and does not show\n\n");
    md.push_str("- It shows how much each site's storage format and accumulation width moves the logits of one small decoder, with every rounding of every matrix product executed exactly as specified.\n");
    md.push_str("- The weights are random and the model has 2 layers; a trained or deeper model can rank its sites differently. The perplexity is that of the reference's own greedy continuation, not of text.\n");
    md.push_str("- Only matrix products, their inputs and the KV cache change format; element-wise work, the residual stream and the attention core stay binary32. FP8 and INT8 with scales are not modeled.\n");
    md.push_str("- Every sum runs in one sequential order. A narrow accumulator's error depends on that order; blocked or tree-shaped kernels were not modeled.\n");
    md
}

fn sensitivity_sentence(r: &PrecisionResult) -> String {
    let one: Vec<&PolicyRun> = r.runs.iter().filter(|x| matches!(x.kind, Kind::OneSite(..))).collect();
    let worst = one
        .iter()
        .max_by(|a, b| a.drift.mean_kl.partial_cmp(&b.drift.mean_kl).expect("finite"));
    let best = one
        .iter()
        .min_by(|a, b| a.drift.mean_kl.partial_cmp(&b.drift.mean_kl).expect("finite"));
    match (worst, best) {
        (Some(w), Some(b)) => format!(
            "\nThe largest single-site drift is {} (mean KL {:.2e}, top-1 agreement {} of {}); the smallest is {} (mean KL {:.2e}).\n",
            w.policy.name, w.drift.mean_kl, w.drift.top1_agree, w.drift.scored, b.policy.name, b.drift.mean_kl
        ),
        _ => String::new(),
    }
}
