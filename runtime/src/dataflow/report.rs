//! JSON and Markdown for the R5 experiment (results/r5-dataflow.*). Every
//! number and every generated sentence comes from the [`DataflowResult`].

use super::experiment::{DataflowResult, Run};
use super::graph::Phase;
use super::machine::Machine;
use crate::json::Json;

fn num(x: f64) -> Json {
    Json::Num(x)
}

fn int(x: u64) -> Json {
    Json::Int(x as i64)
}

fn pct(x: f64) -> String {
    format!("{:.1}%", 100.0 * x)
}

fn phase_json(p: Phase) -> Json {
    match p {
        Phase::Prefill { tokens } => Json::obj(vec![("phase", Json::str("prefill")), ("tokens", int(tokens))]),
        Phase::Decode { batch, context } => Json::obj(vec![
            ("phase", Json::str("decode")),
            ("batch", int(batch)),
            ("context", int(context)),
        ]),
    }
}

fn machine_json(m: &Machine) -> Json {
    Json::obj(vec![
        ("name", Json::str(&m.name)),
        ("array_rows", int(m.rows)),
        ("array_cols", int(m.cols)),
        ("vector_lanes", int(m.lanes)),
        ("sram_bytes", int(m.sram_bytes)),
        ("hbm_bytes_per_cycle", int(m.hbm_bytes_per_cycle)),
        ("assumed_cycle_ns", num(m.cycle_ns)),
    ])
}

fn run_json(r: &Run, m: &Machine) -> Json {
    let b = r.breakdown(m);
    let t = &r.timing;
    Json::obj(vec![
        ("machine", Json::str(&m.name)),
        ("shape", phase_json(r.phase)),
        ("cycles", int(t.cycles())),
        ("useful_macs", int(t.useful_macs())),
        ("issued_macs", int(t.issued_macs())),
        ("hbm_bytes", int(t.hbm_bytes())),
        ("array_utilization", num(r.utilization(m))),
        ("roofline_bound_cycles", int(r.roofline_cycles(m))),
        ("flops_per_hbm_byte", num(r.intensity())),
        (
            "cycles_by_reason",
            Json::obj(vec![
                ("useful_array", num(b.useful)),
                ("padding_or_masked_array", num(b.waste)),
                ("vector", num(b.vector)),
                ("memory_stall", num(b.memory_stall)),
                ("first_load_fill", num(b.fill)),
            ]),
        ),
        (
            "ops",
            Json::Arr(
                t.ops
                    .iter()
                    .map(|o| {
                        Json::obj(vec![
                            ("op", Json::str(o.op.name)),
                            ("cycles", int(o.timeline.cycles)),
                            ("compute_cycles", int(o.timeline.busy)),
                            ("dma_cycles", int(o.timeline.dma)),
                            ("memory_stall", int(o.timeline.memory_stall)),
                            ("fill", int(o.timeline.fill)),
                            ("hbm_bytes", int(o.hbm_bytes)),
                            ("useful_macs", int(o.useful_macs)),
                            ("issued_macs", int(o.issued_macs)),
                            ("chunks", Json::uint(o.chunks)),
                        ])
                    })
                    .collect(),
            ),
        ),
    ])
}

pub fn to_json(r: &DataflowResult, command: &str) -> Json {
    let c = &r.config;
    Json::obj(vec![
        ("command", Json::str(command)),
        (
            "model",
            Json::obj(vec![
                ("hidden", int(c.model.hidden)),
                ("q_heads", int(c.model.q_heads)),
                ("kv_heads", int(c.model.kv_heads)),
                ("head_dim", int(c.model.head_dim)),
                ("ffn", int(c.model.ffn)),
                ("scope", Json::str("one transformer layer, one device")),
            ]),
        ),
        ("machines", Json::Arr(c.machines.iter().map(machine_json).collect())),
        (
            "runs",
            Json::Arr(r.runs.iter().map(|x| run_json(x, &c.machines[x.machine])).collect()),
        ),
    ])
}

/// The op whose cycles dominate, and whether it was compute- or DMA-bound.
fn bound(o: &super::sim::OpTiming) -> &'static str {
    if o.timeline.busy >= o.timeline.dma {
        "compute"
    } else {
        "memory"
    }
}

pub fn to_markdown(r: &DataflowResult, command: &str) -> String {
    let c = &r.config;
    let m0 = &c.machines[0];
    let mut md = String::new();
    md.push_str("# R5: mapping a transformer layer onto a toy accelerator\n\n");
    md.push_str(&format!(
        "Generated by `{command}`. Every number below comes from that run.\n\n"
    ));
    md.push_str("## Setup\n\n");
    md.push_str(&format!(
        "- Graph: one 8B-class transformer layer (hidden {}, {} query and {} KV heads of dimension {}, FFN {}) on one device, BF16 tensors: RMSNorm, Q/K/V projection, RoPE, K/V cache write, attention scores, softmax, attention × V, output projection, residual add, RMSNorm, gate/up projection, SiLU × up, down projection, residual add. Prefill is one sequence attending causally; decode is one new token per sequence with a 1024-token context read from the KV cache.\n",
        c.model.hidden, c.model.q_heads, c.model.kv_heads, c.model.head_dim, c.model.ffn
    ));
    md.push_str(&format!(
        "- Machine (illustrative, not a measured or named device): a {} × {} multiply–accumulate array, {} vector lanes, {} MiB SRAM, 1.5 TB/s HBM, one DMA engine and two chunk buffers. An activation stays in SRAM if it fits in half of it; weights and the KV cache come from HBM.\n",
        m0.rows, m0.cols, m0.lanes, m0.sram_bytes >> 20
    ));
    md.push_str("- Mapping: matrix products in output passes sized to a quarter of SRAM, column blocks of the array width and reduction chunks sized for double buffering; tiles entirely above the causal diagonal are skipped, partly masked tiles are computed in full. Vector ops cost illustrative per-element operation counts. Ops run strictly one after another, so each op's first load is exposed. A chunk's load and the previous chunk's compute overlap (two buffers).\n");
    md.push_str("- Results are in cycles. Two machine variants differ only in the assumed cycle time, which sets HBM bytes per cycle:\n");
    for m in &c.machines {
        md.push_str(&format!(
            "  - {}: {} HBM bytes per cycle.\n",
            m.name, m.hbm_bytes_per_cycle
        ));
    }
    md.push_str("  The second takes FP Play's recorded combinational delay of its FP16 fused multiply–add (Nangate45, ideal interconnect, M12 artifact) as the cycle time. That is an assumption for illustration, not an achievable clock: it ignores pipelining, registers and layout.\n\n");

    md.push_str("## 1. Prefill and decode\n\n");
    md.push_str("Array utilization: useful multiply–accumulates ÷ (array size × cycles). Intensity: FLOPs (2 per useful multiply–accumulate) per HBM byte. Roofline bound: max(useful multiply–accumulates ÷ array size, HBM bytes ÷ bytes per cycle), the fewest cycles this machine allows for this mapping's useful work and HBM traffic. Cycle shares: useful array work / padding or masked array work / vector unit / waiting for the DMA / each op's exposed first load.\n\n");
    md.push_str("| Machine | Shape | Cycles per layer | Roofline bound | × bound | Array utilization | FLOPs per HBM byte | HBM MB | Useful / waste / vector / DMA wait / fill |\n");
    md.push_str("|---|---|---:|---:|---:|---:|---:|---:|---|\n");
    for x in &r.runs {
        let m = &c.machines[x.machine];
        let b = x.breakdown(m);
        let total = x.timing.cycles() as f64;
        md.push_str(&format!(
            "| {} | {} | {} | {} | {:.2} | {} | {:.1} | {:.1} | {} / {} / {} / {} / {} |\n",
            m.name,
            x.phase.name(),
            x.timing.cycles(),
            x.roofline_cycles(m),
            total / x.roofline_cycles(m) as f64,
            pct(x.utilization(m)),
            x.intensity(),
            x.timing.hbm_bytes() as f64 / 1e6,
            pct(b.useful / total),
            pct(b.waste / total),
            pct(b.vector / total),
            pct(b.memory_stall / total),
            pct(b.fill / total),
        ));
    }
    md.push_str(&roofline_sentences(r));

    md.push_str("\n## 2. Op by op\n\n");
    for &phase in &c.detail {
        let Some(x) = r.run(0, phase) else { continue };
        let total = x.timing.cycles() as f64;
        md.push_str(&format!("**{}**, {}:\n\n", phase.name(), m0.name));
        md.push_str("| Op | Cycles | Share | Bound | Array utilization | HBM MB |\n|---|---:|---:|---|---:|---:|\n");
        for o in &x.timing.ops {
            let util = if o.on_array && o.timeline.cycles > 0 {
                pct(o.useful_macs as f64 / (m0.peak_macs() as f64 * o.timeline.cycles as f64))
            } else {
                "–".into()
            };
            md.push_str(&format!(
                "| {} | {} | {} | {} | {} | {:.2} |\n",
                o.op.name,
                o.timeline.cycles,
                pct(o.timeline.cycles as f64 / total),
                bound(o),
                util,
                o.hbm_bytes as f64 / 1e6
            ));
        }
        md.push('\n');
    }

    md.push_str("## What this does and does not show\n\n");
    md.push_str("- It shows, for one explicit machine model and one simple mapping, where a transformer layer's cycles go in prefill and decode, and how far that mapping is from the roofline bound.\n");
    md.push_str("- The mapping puts tokens on the array's rows, so a decode step with fewer than 128 sequences leaves rows idle (padding). A mapping built for matrix–vector products (for example splitting the reduction across rows) is not modeled; decode's distance from its roofline bound is a property of this mapping.\n");
    md.push_str("- Every machine constant is illustrative. The mapping is one simple tiling with no operator fusion, no overlap between ops, no multi-device parallelism and one DMA engine; real compilers and accelerators do better and differ.\n");
    md.push_str("- SRAM bandwidth, bank conflicts, the NoC, power and area are not modeled. Vector-op costs are illustrative operation counts.\n");
    md.push_str("- The recorded FP16 FMA delay is used only as an assumed cycle time; it is a combinational path delay under stated IO constraints, not a clock frequency, and nothing here is a timing, area or power result.\n");
    md
}

fn roofline_sentences(r: &DataflowResult) -> String {
    let mut out = String::new();
    // What limits each run in this mapping: padding, DMA waits or useful work.
    for (i, m) in r.config.machines.iter().enumerate() {
        let worst = r.runs.iter().filter(|x| x.machine == i).max_by(|a, b| {
            let ra = a.timing.cycles() as f64 / a.roofline_cycles(m) as f64;
            let rb = b.timing.cycles() as f64 / b.roofline_cycles(m) as f64;
            ra.partial_cmp(&rb).expect("finite")
        });
        if let Some(x) = worst {
            let b = x.breakdown(m);
            let total = x.timing.cycles() as f64;
            out.push_str(&format!(
                "\n{}: the run furthest from its roofline bound is {} ({:.2}× the bound); padding takes {} of its cycles and waiting for the DMA {}{}.",
                m.name,
                x.phase.name(),
                total / x.roofline_cycles(m) as f64,
                pct(b.waste / total),
                pct(b.memory_stall / total),
                if b.waste > b.memory_stall {
                    ", so in this mapping it is limited by idle array rows, not by HBM"
                } else {
                    ""
                }
            ));
        }
    }
    for (i, m) in r.config.machines.iter().enumerate() {
        let peak = 2.0 * m.peak_macs() as f64;
        let ridge = peak / m.hbm_bytes_per_cycle as f64;
        let below: Vec<String> = r
            .runs
            .iter()
            .filter(|x| x.machine == i && x.intensity() < ridge)
            .map(|x| x.phase.name())
            .collect();
        out.push_str(&format!(
            "\n{}: the roofline's ridge point is {:.1} FLOPs per HBM byte ({} FLOPs per cycle ÷ {} bytes per cycle). Below it (memory-bound by intensity): {}.",
            m.name,
            ridge,
            peak,
            m.hbm_bytes_per_cycle,
            if below.is_empty() { "none".to_string() } else { below.join(", ") }
        ));
    }
    out.push('\n');
    out
}
