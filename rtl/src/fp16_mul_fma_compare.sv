// Original side-by-side hardware paths. Nonfused performs TWO real FP16 operations.
module fp16_mul_fma_compare (
    input logic [15:0] a, b, c,
    output logic [15:0] multiply_result,
    output logic [15:0] fused_result,
    output logic [15:0] nonfused_result,
    output logic [3:0] multiply_flags,
    output logic [3:0] fused_flags,
    output logic [3:0] addition_flags,
    output logic [3:0] nonfused_flags,
    output logic [10:0] mul_significand_a,
    output logic [10:0] mul_significand_b,
    output logic mul_product_sign,
    output logic signed [7:0] mul_product_exponent,
    output logic [21:0] mul_exact_product,
    output logic [79:0] mul_aligned_product,
    output logic [63:0] mul_aligned_addend,
    output logic [80:0] mul_arithmetic_magnitude,
    output logic mul_result_sign,
    output logic mul_special_case,
    output logic [6:0] mul_normalization_shift,
    output logic [6:0] mul_discard_count,
    output logic [11:0] mul_retained_significand,
    output logic mul_guard_bit,
    output logic mul_round_bit,
    output logic mul_sticky_bit,
    output logic mul_increment,
    output logic [5:0] mul_exponent_rounded,
    output logic mul_tiny_after_precision_rounding,
    output logic [10:0] fma_significand_a,
    output logic [10:0] fma_significand_b,
    output logic fma_product_sign,
    output logic signed [7:0] fma_product_exponent,
    output logic [21:0] fma_exact_product,
    output logic [79:0] fma_aligned_product,
    output logic [63:0] fma_aligned_addend,
    output logic [80:0] fma_arithmetic_magnitude,
    output logic fma_result_sign,
    output logic fma_special_case,
    output logic [6:0] fma_normalization_shift,
    output logic [6:0] fma_discard_count,
    output logic [11:0] fma_retained_significand,
    output logic fma_guard_bit,
    output logic fma_round_bit,
    output logic fma_sticky_bit,
    output logic fma_increment,
    output logic [5:0] fma_exponent_rounded,
    output logic fma_tiny_after_precision_rounding,
    output logic add_effective_b_sign,
    output logic [5:0] add_exponent_difference,
    output logic [39:0] add_aligned_a,
    output logic [39:0] add_aligned_b,
    output logic [40:0] add_arithmetic_magnitude,
    output logic [5:0] add_normalization_shift,
    output logic [40:0] add_normalized_magnitude,
    output logic [5:0] add_discard_count,
    output logic [11:0] add_retained_significand,
    output logic add_guard_bit,
    output logic add_round_bit,
    output logic add_sticky_bit,
    output logic add_increment,
    output logic [4:0] add_exponent_rounded,
    output logic add_special_case
);
    fp16_mul mul_path (
        .a(a), .b(b),
        .result(multiply_result),
        .invalid(multiply_flags[3]),
        .overflow(multiply_flags[2]),
        .underflow(multiply_flags[1]),
        .inexact(multiply_flags[0]),
        .significand_a(mul_significand_a),
        .significand_b(mul_significand_b),
        .product_sign(mul_product_sign),
        .product_exponent(mul_product_exponent),
        .exact_product(mul_exact_product),
        .aligned_product(mul_aligned_product),
        .aligned_addend(mul_aligned_addend),
        .arithmetic_magnitude(mul_arithmetic_magnitude),
        .result_sign(mul_result_sign),
        .special_case(mul_special_case),
        .normalization_shift(mul_normalization_shift),
        .discard_count(mul_discard_count),
        .retained_significand(mul_retained_significand),
        .guard_bit(mul_guard_bit),
        .round_bit(mul_round_bit),
        .sticky_bit(mul_sticky_bit),
        .increment(mul_increment),
        .exponent_rounded(mul_exponent_rounded),
        .tiny_after_precision_rounding(mul_tiny_after_precision_rounding)
    );
    fp16_fma fma_path (
        .a(a), .b(b), .c(c),
        .result(fused_result),
        .invalid(fused_flags[3]),
        .overflow(fused_flags[2]),
        .underflow(fused_flags[1]),
        .inexact(fused_flags[0]),
        .significand_a(fma_significand_a),
        .significand_b(fma_significand_b),
        .product_sign(fma_product_sign),
        .product_exponent(fma_product_exponent),
        .exact_product(fma_exact_product),
        .aligned_product(fma_aligned_product),
        .aligned_addend(fma_aligned_addend),
        .arithmetic_magnitude(fma_arithmetic_magnitude),
        .result_sign(fma_result_sign),
        .special_case(fma_special_case),
        .normalization_shift(fma_normalization_shift),
        .discard_count(fma_discard_count),
        .retained_significand(fma_retained_significand),
        .guard_bit(fma_guard_bit),
        .round_bit(fma_round_bit),
        .sticky_bit(fma_sticky_bit),
        .increment(fma_increment),
        .exponent_rounded(fma_exponent_rounded),
        .tiny_after_precision_rounding(fma_tiny_after_precision_rounding)
    );
    fp16_addsub add_path (
        .a(multiply_result), .b(c), .subtract(1'b0),
        .result(nonfused_result),
        .invalid(addition_flags[3]),
        .overflow(addition_flags[2]),
        .underflow(addition_flags[1]),
        .inexact(addition_flags[0]),
        .effective_b_sign(add_effective_b_sign),
        .exponent_difference(add_exponent_difference),
        .aligned_a(add_aligned_a),
        .aligned_b(add_aligned_b),
        .arithmetic_magnitude(add_arithmetic_magnitude),
        .normalization_shift(add_normalization_shift),
        .normalized_magnitude(add_normalized_magnitude),
        .discard_count(add_discard_count),
        .retained_significand(add_retained_significand),
        .guard_bit(add_guard_bit),
        .round_bit(add_round_bit),
        .sticky_bit(add_sticky_bit),
        .increment(add_increment),
        .exponent_rounded(add_exponent_rounded),
        .special_case(add_special_case)
    );
    assign nonfused_flags = multiply_flags | addition_flags;
endmodule
